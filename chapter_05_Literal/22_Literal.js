let age = "suresh";//This is a string literal assigned to a variable 'age'
let isStudent = true;//This is a boolean literal assigned to a variable 'isStudent'
let pi = 3.14;//This is a numeric literal assigned to a variable 'pi'
let name = "ganesh"//This is a string literal assigned to a variable 'name'
let nullValue = null;//This is a null literal assigned to a variable 'nullValue'
let undefinedValue;//This variable is declared but not assigned so it has the value 'undefined'

//typeof is a operator which tells you what is the data type of that

console.log(typeof age);//String
console.log(typeof isStudent);//boolean
console.log(typeof pi);//number
console.log(typeof name);//string
console.log(typeof nullValue);//object
console.log(typeof undefinedValue);//undefined