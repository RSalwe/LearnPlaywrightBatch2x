let arr = [1, 2, 3];
console.log(arr);

// Add to END
arr.push(4);
console.log(arr);

//Remove to END
arr.pop();
console.log(arr);

//Add multiple values in Array
arr.push(4, 5);
console.log(arr);

//Add element to begining
arr.unshift(0);
console.log(arr);

//Remove element to begining
arr.shift();
console.log(arr);