// // Pre Increment
let a = 10;
let b = ++a;// Increment the value of a by 1
console.log(b);//11
console.log(a);//11
// //Pre Increment -> ++a -> Increment the value first and then assign to a

//********Decrement Operator***********

// Pre Decrement
let a1 = 10;
let b1 = --a1;// Decrement the value of a1 by 1
console.log(b1);//9
console.log(a1);//9

// Post Decrement
let x1 = 10;
let y1 = x1--;// Assign the value and Decrement the value of x1 by 1
console.log(y1);//10
console.log(x1);//9