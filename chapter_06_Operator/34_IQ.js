let x = 10;
//Below is Compound Operator
x += 10;//This is x = x + 10;
console.log(x);//x = 20

//Below will take x = 20
x -= 3;//This is x = x-3
console.log(x);//x = 17

//Below will take x = 17
x *= 3;//This is x = x*3;
console.log(x);

//Below will take x = 51
x /= 17;//This is x = x /17
console.log(x);

//Below will take x = 3
x %= 3;//This is x = x % 3
console.log(x);