let day = 1;
//ex. if monday = 1, tuesday = 2, .........
switch (day) {
    case 1:
        console.log("Monday");
        let a = 10;
        let b = 20;
        console.log(a + b);
        break;
    case 2:
        console.log("Tuesday");
        break;
    case 3:
        console.log("Wednesday");
        break;
    case 4:
        console.log("Thursday");
        break;
    case 5:
        console.log("Friday");
        break;
    case 6:
        console.log("Saturday");
        break;
    case 7:
        console.log("Sunday");
        break;
    default:
        console.log("There is no such day!!")
}